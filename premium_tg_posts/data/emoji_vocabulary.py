def normalize(value: str | None) -> str:
    """Drop variation selectors and skin tones so keys stay comparable."""
    if not value:
        return ""
    return "".join(char for char in value if char not in VARIATION_SELECTORS and char not in SKIN_TONES)


def lookup(alt: str | None) -> tuple[str, tuple[str, ...]] | None:
    """Best entry for a fallback symbol.

    Tries the symbol as-is, then normalized, then the part before the first ZWJ,
    so "🤷‍♂️" still resolves through "🤷" when no gendered entry exists.
    """
    if not alt:
        return None
    for candidate in (alt, normalize(alt)):
        if candidate in VOCABULARY:
            return VOCABULARY[candidate]

    base = normalize(alt).split(ZWJ)[0]
    if base and base in VOCABULARY:
        return VOCABULARY[base]
    return None
